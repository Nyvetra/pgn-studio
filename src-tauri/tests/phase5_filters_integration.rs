    let eco_file = eco_file_path();
    let mut spec = base_spec(
        vec![filters_fixture("date-edge-1999.pgn")],
        dest.path().to_path_buf(),
        "date-bare-year",
    );
    // A bare "1999" with Le — the compiler must expand this to
    // "1999.12.31", never emit it verbatim (engine::criteria::render_date_value).
    spec.filters.tag_rules = vec![tag_rule(TagName::Date, TagOp::Le, "1999")];

    run_succeeding(spec, &engine, &caps, jobs_root.path(), &eco_file).await;
    let output_path = dest.path().join("date-bare-year.pgn");
