/// Positive + the "no-op is prefix, not equality" trap in one test:
/// `Player "Tal"` matches White=Tal (G1), Black=Tal (G2), AND White=Talbot
/// (G3) — a real player named "Talbot" is not a typo, it is design-02's own
/// cited example that a no-op match is `strncmp`-based prefix matching.
#[tokio::test]
async fn player_either_color_matches_by_prefix_including_the_talbot_trap() {
    let (engine, caps) = resolve_engine().await;
    let dest = tempfile::tempdir().unwrap();
    let jobs_root = tempfile::tempdir().unwrap();
    let eco_file = eco_file_path();
    let mut spec = base_spec(
        vec![filters_fixture("players-results-dates.pgn")],
        dest.path().to_path_buf(),
        "player-either",
    );
    spec.filters.tag_rules = vec![tag_rule(TagName::Player, TagOp::Prefix, "Tal")];

    let result = run_succeeding(spec, &engine, &caps, jobs_root.path(), &eco_file).await;
    let output_path = dest.path().join("player-either.pgn");
    assert_eq!(count_games_in_file(&output_path).unwrap(), 3);
    let text = read_to_string(&output_path);
    assert!(text.contains("[White \"Tal, Mikhail\"]"), "White = Tal");
    assert!(text.contains("[Black \"Tal, Mikhail\"]"), "Black = Tal");
    assert!(
        text.contains("[White \"Talbot, Toby\"]"),
        "\"Talbot\" must ALSO match a \"Tal\" prefix filter — this is not a bug"
    );
    assert!(
        !text.contains("Fischer") && !text.contains("Чайковский"),
        "unrelated players must be excluded (negative control)"
    );
    let _ = result;
}

