//! Phase 5 integration tests (architecture.md §24 Phase 5 exit criterion:
//! "Each filter has at least one positive, negative, and combination test.").
//!
//! Mirrors `phase4_integration.rs`'s pattern exactly: real fixture PGNs, the
//! real orchestrator (`jobs::run_job`), the real checksum-verified bundled
//! sidecar — no mocks. Every expected match count below was produced by
//! actually running the pinned sidecar directly against these exact
//! fixtures during this task and reviewing the output, never hand-guessed
//! (architecture.md §4.3, §20.2; task instruction "Golden outputs must be
//! generated by the real engine and reviewed — never hand-written").
//!
//! Covers every §13.4 MVP filter: player (either)/White/Black, result
//! (specific + decisive-only), date/year range, Elo range (either/White/
//! Black), ECO code/range, minimum/maximum moves, checkmates-only, and
//! standard-start-only vs. include-SetUp/FEN. Also covers the task's
//! cross-cutting semantics (criteria-file encoding proven end to end, not
//! just on bytes; CR/LF/NUL rejection; escaping/containment; Unicode
//! round-trip; filters combined with cleanup and dedup; an all-excluded
//! filter publishing an honest, non-crashing empty result) and, as time
//! permitted (task §D, explicitly optional — see this file's final section
//! and the task report for what is/isn't wired into the UI), the two
//! advanced filters FEN pattern and textual opening-line variations.
//!
//! **Two findings from this phase correct earlier documentation** (full
//! evidence inline at each citation below):
//!
//! 1. (Headline; full evidence in `engine::criteria::tag_is_numeric`'s doc
//!    comment, `src-tauri/src/engine/criteria.rs`.) DECISIONS-LEDGER.md
//!    D-010 documented ECO's five broken relational/equality operators
//!    (`<`, `<=`, `>`, `>=`, `=`) as an ECO-specific fact. Fresh empirical
//!    testing for this phase proved it is a **general property of every
//!    non-numeric tag** — including, critically, `Result`. Before this
//!    phase's fix, `src/state/filterMapping.ts` compiled *every* Result
//!    checkbox on the Filters screen (White wins / Black wins / Draw /
//!    Other / Decisive-only) to `Result = "<value>"`, which silently
//!    matched **zero games, always**, for any job that used a Result
//!    filter — a live, shipped, ship-blocking bug, not a hypothetical one.
//!    Both the Rust compiler (`engine::criteria`) and the frontend
//!    (`filterMapping.ts`) are fixed in this phase; several tests below
//!    (`result_*`) are the real-engine proof of both the bug and the fix.
//! 2. (See `a_tag_missing_entirely_never_matches_even_when_every_criterion_is_not_equal`
//!    below.) design-02 §1.5.1 claims a game missing a criteria tag
//!    matches "unless every criterion on that tag is `<>`". Fresh empirical
//!    testing disproves the exception: a game missing a tag entirely never
//!    matches, `<>` included, with no carve-out. This one required no code
//!    fix — the shipped UI copy already states the simpler, correct,
//!    exception-free rule — but it is pinned here as a regression guard and
//!    a correction to the design document's own claim.

