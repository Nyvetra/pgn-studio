/// **The headline empirical finding of this phase**, pinned end to end.
/// Deliberately bypasses the command compiler (which now correctly REJECTS
/// `Result` + `Eq` at compile time — see `command_compiler`'s capability/
/// structural validation and `engine::criteria`'s
/// `result_numeric_relational_operators_are_rejected` unit test) and spawns
/// the real sidecar directly with a hand-built criteria file, exactly as
/// `phase4_integration.rs`'s `eco_separated_form_is_catastrophic_empirical_proof`
/// does for its own historical hazard. Proves that `Result = "1-0"` — what
/// `src/state/filterMapping.ts` shipped before this phase's fix — silently
/// matches ZERO games, even though 3 of the 6 fixture games genuinely have
/// `Result "1-0"`, while the corrected no-op form matches all 3.
#[tokio::test]
async fn result_equality_operator_would_have_silently_matched_nothing_empirical_proof() {
    let (engine, _caps) = resolve_engine().await;
    let workdir = tempfile::tempdir().unwrap();
    let input_path = filters_fixture("players-results-dates.pgn");

    let buggy_criteria_path = workdir.path().join("buggy.txt");
    std::fs::write(&buggy_criteria_path, "Result = \"1-0\"\n").unwrap();
    let correct_criteria_path = workdir.path().join("correct.txt");
    std::fs::write(&correct_criteria_path, "Result \"1-0\"\n").unwrap();

    let run_with = |criteria: &Path, out_name: &str| {
        let out_path = workdir.path().join(out_name);
        let mut t_flag = OsString::from("-t");
        t_flag.push(criteria);
        let mut o_flag = OsString::from("-o");
        o_flag.push(&out_path);
        let output = std::process::Command::new(engine.path())
            .current_dir(workdir.path())
            .arg("-s")
            .arg("--summary")
            .arg(t_flag)
            .arg(o_flag)
            .arg(&input_path)
            .output()
            .expect("the real sidecar must spawn");
        assert_eq!(
            output.status.code(),
            Some(0),
            "engine run itself must succeed"
        );
        count_games_in_file(&out_path).unwrap_or(0)
    };

    let buggy_matches = run_with(&buggy_criteria_path, "buggy-out.pgn");
    let correct_matches = run_with(&correct_criteria_path, "correct-out.pgn");

    assert_eq!(
        buggy_matches, 0,
        "\"Result = \\\"1-0\\\"\" must silently match ZERO games even though 3 of 6 games \
         genuinely have that Result — this is the exact bug that shipped in \
         filterMapping.ts before this phase's fix"
    );
    assert_eq!(
        correct_matches, 3,
        "the corrected no-op/prefix form must match the 3 games that actually have Result \"1-0\""
    );
}

