/// Same shape/defaults as `phase4_integration.rs`'s `base_spec`: `Process`
/// mode, inputs in argument order, `Fail` conflict policy, no cleanup/
/// filters/ECO, no duplicate handling, no log/manifest artifacts. Each test
/// mutates only the fields its scenario cares about — almost always just
/// `filters`.
fn base_spec(inputs: Vec<PathBuf>, destination_dir: PathBuf, base_name: &str) -> JobSpec {
    JobSpec {
        schema_version: CURRENT_SCHEMA_VERSION,
        id: Uuid::new_v4(),
        name: "phase5-filters-integration-test".to_string(),
        inputs: inputs
            .into_iter()
            .enumerate()
            .map(|(i, path)| InputFile {
                display_name: path.display().to_string(),
                path,
                priority: i as u32,
            })
            .collect(),
        output: OutputPlan {
            directory: destination_dir,
            base_name: base_name.to_string(),
            unique_games: true,
            duplicate_games: DuplicateOutput::None,
            log_file: false,
            manifest: false,
            always_create_audit: false,
            conflict_policy: ConflictPolicy::Fail,
            confirmed_replace: false,
        },
        operations: OperationPlan {
            mode: JobMode::Process,
            duplicates: DuplicatePolicy::None,
            cleanup: no_cleanup(),
            broken: BrokenOutput::Discard,
            eco: EcoOptions { enabled: false },
            output_notation: OutputNotation::San,
            check_file: None,
        },
        filters: no_filters(),
        runtime: RuntimeOptions {
            use_external_duplicate_table: false,
            count_output_games: true,
        },
    }
}

fn tag_rule(tag: TagName, op: TagOp, value: &str) -> TagRule {
    TagRule {
        tag,
        op,
        value: value.to_string(),
    }
}

/// Runs `spec` through the real orchestrator and asserts it succeeded,
/// returning the result for further assertions (matches
/// `phase4_integration.rs`'s inline pattern, factored out here because
/// nearly every test in this file needs it).
async fn run_succeeding(
    spec: JobSpec,
    engine: &EngineExecutable,
    caps: &EngineCapabilities,
    jobs_root: &Path,
    eco_file: &Path,
) -> pgn_studio_lib::domain::JobResult {
    let state = AppState::new();
    let ctx = RunJobContext {
        caps,
        engine,
        jobs_root,
        eco_file,
    };
    let result = run_job(spec, &ctx, &state, &NullEventSink).await.unwrap();
    assert_eq!(result.status, JobStatus::Succeeded, "{:?}", result.error);
    result
}

